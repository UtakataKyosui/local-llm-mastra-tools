#!/usr/bin/env python3
"""Regenerates src/lib/ollama-tool-models.ts from the Ollama library's "tools" category."""

import datetime
import html
import json
import re
import time
import urllib.request
from pathlib import Path

SOURCE_URL = "https://ollama.com/search?c=tools&o=popular"
OUTPUT = Path(__file__).resolve().parent.parent / "src/lib/ollama-tool-models.ts"
MAX_PAGES = 50


def fetch(page: int) -> str:
    # The search page loads further results with htmx; the HX-Request header returns that partial.
    req = urllib.request.Request(
        f"{SOURCE_URL}&page={page}",
        headers={"User-Agent": "Mozilla/5.0", "HX-Request": "true"},
    )
    with urllib.request.urlopen(req, timeout=30) as res:
        return res.read().decode()


def badges(block: str, color_class: str) -> list[str]:
    return [b.strip() for b in re.findall(rf'{re.escape(color_class)}[^>]*>([^<]+)</span>', block)]


def parse(doc: str) -> list[dict]:
    models = []
    for block in re.findall(r"<li[^>]*items-baseline[^>]*>(.*?)</li>", doc, re.S):
        name = re.search(r'href="/library/([^"]+)"', block)
        if not name:
            continue
        description = re.search(r'<p class="max-w-lg[^"]*">(.*?)</p>', block, re.S)
        pulls = re.search(r'<span >([\d.]+[KMB]?)</span>\s*<span class="hidden sm:flex">&nbsp;Pulls', block)
        models.append(
            {
                "name": name.group(1),
                "description": html.unescape(re.sub(r"\s+", " ", description.group(1)).strip()) if description else "",
                "capabilities": badges(block, "bg-indigo-50"),
                "sizes": badges(block, "bg-[#ddf4ff]"),
                "cloud": "cloud" in badges(block, "bg-cyan-50"),
                "pulls": pulls.group(1) if pulls else "",
            }
        )
    return models


def main() -> None:
    models: list[dict] = []
    seen: set[str] = set()
    for page in range(1, MAX_PAGES + 1):
        batch = [m for m in parse(fetch(page)) if m["name"] not in seen]
        if not batch:
            break
        seen.update(m["name"] for m in batch)
        models += batch
        time.sleep(0.5)
    if not models:
        raise SystemExit("No models parsed; the ollama.com markup may have changed.")

    fetched_at = datetime.date.today().isoformat()
    body = json.dumps(models, ensure_ascii=False, indent=2)
    OUTPUT.write_text(
        "// Generated by scripts/update-ollama-tool-models.py. Run `pnpm models:update-tools` to refresh.\n"
        "\n"
        "export interface OllamaToolModel {\n"
        "  name: string;\n"
        "  description: string;\n"
        "  capabilities: string[];\n"
        "  // Empty when the model only runs on Ollama's cloud.\n"
        "  sizes: string[];\n"
        "  // Whether a cloud variant exists; local sizes may exist as well.\n"
        "  cloud: boolean;\n"
        "  pulls: string;\n"
        "}\n"
        "\n"
        f"export const OLLAMA_TOOL_MODELS_SOURCE = '{SOURCE_URL}';\n"
        f"export const OLLAMA_TOOL_MODELS_FETCHED_AT = '{fetched_at}';\n"
        "\n"
        f"export const OLLAMA_TOOL_MODELS: OllamaToolModel[] = {body};\n"
    )
    print(f"Wrote {len(models)} models to {OUTPUT}")


if __name__ == "__main__":
    main()
